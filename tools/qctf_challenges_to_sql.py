#!/usr/bin/env python3
"""
Build the SQL that loads QCTF competition challenges into Supabase.

The input JSON holds plaintext flags, so keep it in qctf-private/ (gitignored) and
never commit it. The output SQL contains only SHA-256 hashes of the flags; run it with
the Supabase MCP `execute_sql` tool or the Supabase SQL editor.

Usage:
    python tools/qctf_challenges_to_sql.py qctf-private/challenges.json > qctf-private/load_challenges.sql

Input: a JSON array of objects with these keys:
    id          "PQC-02" (uppercase letters, digits and hyphens)
    trackId     qml | qaoa | pqc | q-chemistry | quantum-simulation
    title       short title
    summary     one-line card text
    statement   full problem statement (newlines allowed)
    difficulty  easy | hard | advanced
    points      positive integer
    block       practice | block_1 | block_2 | final
    flag        the exact accepted flag, e.g. "qctf{3}" (surrounding spaces are ignored)
    tags        optional list of strings
    attachments optional list of {"label": ..., "url": ...}
    sortOrder   optional integer (defaults to the position in the file)

Re-running the output updates existing rows in place (upsert on id).
"""

import hashlib
import json
import re
import sys

TRACKS = {"qml", "qaoa", "pqc", "q-chemistry", "quantum-simulation"}
DIFFICULTIES = {"easy", "hard", "advanced"}
BLOCKS = {"practice", "block_1", "block_2", "final"}
ID_PATTERN = re.compile(r"^[A-Z0-9][A-Z0-9-]{1,31}$")
QUOTE_TAG = "$qctf$"


def quote(value: str) -> str:
    """Dollar-quote a string so statements can contain quotes and backslashes unchanged."""
    if QUOTE_TAG in value:
        raise ValueError(f"text may not contain {QUOTE_TAG}")
    return f"{QUOTE_TAG}{value}{QUOTE_TAG}"


def validate(index: int, item: dict) -> list:
    problems = []
    where = f"challenge #{index + 1} ({item.get('id', 'no id')})"
    if not ID_PATTERN.match(str(item.get("id", ""))):
        problems.append(f"{where}: id must be uppercase letters, digits and hyphens")
    if item.get("trackId") not in TRACKS:
        problems.append(f"{where}: trackId must be one of {sorted(TRACKS)}")
    if item.get("difficulty") not in DIFFICULTIES:
        problems.append(f"{where}: difficulty must be one of {sorted(DIFFICULTIES)}")
    if item.get("block") not in BLOCKS:
        problems.append(f"{where}: block must be one of {sorted(BLOCKS)}")
    if not isinstance(item.get("points"), int) or item["points"] <= 0:
        problems.append(f"{where}: points must be a positive integer")
    for key in ("title", "statement", "flag"):
        if not isinstance(item.get(key), str) or not item[key].strip():
            problems.append(f"{where}: {key} is required")
    return problems


def to_sql(items: list) -> str:
    rows = []
    for index, item in enumerate(items):
        flag_hash = hashlib.sha256(item["flag"].strip().encode("utf-8")).hexdigest()
        tags = item.get("tags") or []
        tags_sql = "ARRAY[" + ", ".join(quote(str(t)) for t in tags) + "]::text[]" if tags else "'{}'::text[]"
        attachments = json.dumps(item.get("attachments") or [], ensure_ascii=False)
        rows.append(
            "    ("
            + ", ".join(
                [
                    quote(item["id"]),
                    quote(item["trackId"]),
                    quote(item["title"].strip()),
                    quote((item.get("summary") or "").strip()),
                    quote(item["statement"].strip()),
                    quote(item["difficulty"]),
                    str(item["points"]),
                    tags_sql,
                    quote(item["block"]),
                    f"{quote(attachments)}::jsonb",
                    quote(flag_hash),
                    str(item.get("sortOrder", (index + 1) * 10)),
                ]
            )
            + ")"
        )

    return (
        "-- Generated by tools/qctf_challenges_to_sql.py. Contains flag hashes only.\n"
        "INSERT INTO public.qctf_challenges\n"
        "    (id, track_id, title, summary, statement, difficulty, points, tags, block, attachments, flag_hash, sort_order)\n"
        "VALUES\n"
        + ",\n".join(rows)
        + "\nON CONFLICT (id) DO UPDATE SET\n"
        "    track_id = EXCLUDED.track_id,\n"
        "    title = EXCLUDED.title,\n"
        "    summary = EXCLUDED.summary,\n"
        "    statement = EXCLUDED.statement,\n"
        "    difficulty = EXCLUDED.difficulty,\n"
        "    points = EXCLUDED.points,\n"
        "    tags = EXCLUDED.tags,\n"
        "    block = EXCLUDED.block,\n"
        "    attachments = EXCLUDED.attachments,\n"
        "    flag_hash = EXCLUDED.flag_hash,\n"
        "    sort_order = EXCLUDED.sort_order,\n"
        "    updated_at = now();\n"
    )


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding="utf-8") as handle:
        items = json.load(handle)
    if not isinstance(items, list) or not items:
        print("Input must be a non-empty JSON array.", file=sys.stderr)
        return 1

    problems = [p for i, item in enumerate(items) for p in validate(i, item)]
    ids = [item.get("id") for item in items]
    problems += [f"duplicate id {dup}" for dup in sorted({i for i in ids if ids.count(i) > 1})]
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1

    sys.stdout.reconfigure(encoding="utf-8")
    sys.stdout.write(to_sql(items))
    print(f"{len(items)} challenges written.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
