#!/usr/bin/env python3
"""
Export Verified Masterclass Certificate Recipients
Qiskit Fall Fest 2026 (SRM University-AP)

Reconciles:
1. Non-hackathon participants (tools/non_hackathon_pass_recipients.csv)
2. Hackathon participants (c:\\Users\\sahgy\\Downloads\\all_hackathon_participants.csv)
3. Fresh Unstop Export (c:\\Users\\sahgy\\Downloads\\Regn_1758795_BasicInfo_20261017_1847_NoFilters.csv)
4. Quiz progress cache (data/quiz_progress_cache.json)

Unlike the On-Campus General Pass, the Verified Masterclass Certificate is open
to ALL festival participants (both Hackathon participants and Non-Hackathon students).

Filters:
- Strictly EXCLUDES protected faculty/speakers (sazzadali.b@srmap.edu.in, gangireddy.s@srmap.edu.in, etc.)
- Strictly EXCLUDES administrative, mentor, and internal test accounts
- Sanitizes all names, completely eliminating Unstop autogenerated codes

Output Columns:
Email, Full Name, Institution, Phone, Quizzes_Passed, Certificate_Email_Status
"""

import os
import sys
import csv
import json
import re

PROTECTED_EMAILS = {
    "sazzadali.b@srmap.edu.in",
    "gangireddy.s@srmap.edu.in",
    "varsha.s@srmap.edu.in",
    "qiskitfallfest@srmap.edu.in",
    "qiskitfallfest2026@gmail.com",
    "sahgyan9@gmail.com",
}

UNSTOP_PATH = r"c:\Users\sahgy\Downloads\Regn_1758795_BasicInfo_20261017_1847_NoFilters.csv"
HACKATHON_PATH = r"c:\Users\sahgy\Downloads\all_hackathon_participants.csv"
NON_HACK_PATH = os.path.join(os.path.dirname(__file__), "non_hackathon_pass_recipients.csv")
PROGRESS_CACHE_PATH = os.path.join(os.path.dirname(os.path.dirname(__file__)), "data", "quiz_progress_cache.json")

def is_code_or_garbage(name: str) -> bool:
    if not name:
        return True
    name = name.strip()
    if len(name) < 2:
        return True
    if re.match(r"^5\d{5}-", name):
        return True
    if re.match(r"^U[0-9A-Z]{7}$", name):
        return True
    if name.startswith("4_KABOOTAR"):
        return True
    if re.match(r"^[A-Z0-9_-]{8,}$", name, re.IGNORECASE) and not re.search(r"[a-z]", name):
        return True
    return False

def clean_name(raw: str) -> str:
    if not raw:
        return ""
    n = " ".join(raw.strip().split())
    # Remove leading roll numbers like AP23110010045, 2300030118, etc.
    m = re.match(r"^(\d{2,4}[A-Za-z0-9]{3,8}\s+)(.*)$", n)
    if m and len(m.group(2).strip()) > 2:
        n = m.group(2).strip()
    return n.title()

def main():
    print("Loading quiz progress data...")
    quiz_progress = {}
    if os.path.exists(PROGRESS_CACHE_PATH):
        try:
            with open(PROGRESS_CACHE_PATH, "r", encoding="utf-8") as f:
                records = json.load(f)
                for r in records:
                    em = (r.get("email") or "").strip().lower()
                    cnt = r.get("passed_quizzes", 0)
                    if em:
                        quiz_progress[em] = cnt
            print(f"-> Loaded {len(quiz_progress)} quiz progress records.")
        except Exception as e:
            print(f"-> Error reading progress cache: {e}")
    else:
        print("-> Notice: Progress cache not found at", PROGRESS_CACHE_PATH)

    recipients_map = {}

    # 1. Ingest non-hackathon recipients (already cleaned)
    if os.path.exists(NON_HACK_PATH):
        print(f"Loading non-hackathon participants from {NON_HACK_PATH}...")
        with open(NON_HACK_PATH, "r", encoding="utf-8", errors="replace") as f:
            reader = csv.DictReader(f)
            for row in reader:
                em = (row.get("Email") or "").strip().lower()
                if not em or "@" not in em:
                    continue
                recipients_map[em] = {
                    "Email": em,
                    "Full Name": clean_name(row.get("Full Name") or ""),
                    "Institution": (row.get("Institution") or "SRM University-AP").strip(),
                    "Phone": (row.get("Phone") or "").strip(),
                }
        print(f"-> Ingested {len(recipients_map)} non-hackathon entries.")

    # 2. Ingest hackathon participants
    if os.path.exists(HACKATHON_PATH):
        print(f"Loading hackathon participants from {HACKATHON_PATH}...")
        hack_count = 0
        with open(HACKATHON_PATH, "r", encoding="utf-8", errors="replace") as f:
            reader = csv.DictReader(f)
            for row in reader:
                em = (row.get("Email") or "").strip().lower()
                if not em or "@" not in em:
                    continue
                name = clean_name(row.get("Participant Name") or "")
                if em not in recipients_map:
                    recipients_map[em] = {
                        "Email": em,
                        "Full Name": name,
                        "Institution": "SRM University-AP" if em.endswith("@srmap.edu.in") else "College / University",
                        "Phone": "",
                    }
                    hack_count += 1
                elif not recipients_map[em]["Full Name"] and name:
                    recipients_map[em]["Full Name"] = name
        print(f"-> Ingested {hack_count} new hackathon entries (Total pool: {len(recipients_map)}).")

    # 3. Supplement with fresh Unstop export (phone numbers, institutions, names)
    if os.path.exists(UNSTOP_PATH):
        print(f"Enriching with Unstop registration data from {UNSTOP_PATH}...")
        with open(UNSTOP_PATH, "r", encoding="utf-8", errors="replace") as f:
            reader = csv.DictReader(f)
            for row in reader:
                em = (row.get("Candidate's Email") or "").strip().lower()
                if not em or "@" not in em:
                    continue
                raw_name = (row.get("Candidate's Name") or "").strip()
                mobile = (row.get("Candidate's Mobile") or "").strip()
                org = (row.get("Candidate's Organisation") or "").strip()
                
                if em not in recipients_map:
                    recipients_map[em] = {
                        "Email": em,
                        "Full Name": clean_name(raw_name) if not is_code_or_garbage(raw_name) else "",
                        "Institution": org or ("SRM University-AP" if em.endswith("@srmap.edu.in") else "College / University"),
                        "Phone": mobile,
                    }
                else:
                    if not recipients_map[em]["Phone"] and mobile:
                        recipients_map[em]["Phone"] = mobile
                    if (not recipients_map[em]["Institution"] or recipients_map[em]["Institution"] == "College / University") and org:
                        recipients_map[em]["Institution"] = org
                    if (not recipients_map[em]["Full Name"] or is_code_or_garbage(recipients_map[em]["Full Name"])) and not is_code_or_garbage(raw_name):
                        recipients_map[em]["Full Name"] = clean_name(raw_name)
        print(f"-> Enriched total pool: {len(recipients_map)} participants.")

    # 4. Filter, sanitize, and format rows
    final_rows = []
    qualified_count = 0
    in_progress_count = 0

    for em in sorted(recipients_map.keys()):
        if em in PROTECTED_EMAILS or "sazzadali.b" in em or "gangireddy.s" in em:
            continue

        item = recipients_map[em]
        name = item["Full Name"]
        if not name or is_code_or_garbage(name):
            prefix = em.split("@")[0]
            clean_prefix = re.sub(r"[\._\d]+", " ", prefix).strip()
            name = clean_prefix.title() if len(clean_prefix) >= 2 else "Learner"

        passed = quiz_progress.get(em, 0)
        if passed >= 5:
            progress_str = f"{passed}/5 (Qualified)"
            qualified_count += 1
        elif passed > 0:
            progress_str = f"{passed}/5"
            in_progress_count += 1
        else:
            progress_str = "0/5"

        final_rows.append({
            "Email": em,
            "Full Name": name,
            "Institution": item["Institution"] or "SRM University-AP",
            "Phone": item["Phone"] or "",
            "Quizzes_Passed": progress_str,
            "Certificate_Email_Status": "",
        })

    fieldnames = [
        "Email",
        "Full Name",
        "Institution",
        "Phone",
        "Quizzes_Passed",
        "Certificate_Email_Status"
    ]

    out_clean = r"c:\Users\sahgy\Downloads\certificate_recipients_clean.csv"
    with open(out_clean, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(final_rows)

    out_tools = os.path.join(os.path.dirname(__file__), "certificate_recipients.csv")
    with open(out_tools, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(final_rows)

    print("\n============================================================")
    print("SUCCESS: Masterclass Certificate Audience Export Complete")
    print("============================================================")
    print(f"Total Audience Pool: {len(final_rows)} participants")
    print(f"- Fully Qualified (>= 5 quizzes passed): {qualified_count}")
    print(f"- In Progress (1 to 4 quizzes passed):   {in_progress_count}")
    print(f"- Enrolled / Yet to Start (0 quizzes):   {len(final_rows) - qualified_count - in_progress_count}")
    print(f"\nFiles generated:")
    print(f"1. {out_clean}")
    print(f"2. {out_tools}")
    print("============================================================")

if __name__ == "__main__":
    main()
