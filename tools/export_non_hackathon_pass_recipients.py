def supabase_get(endpoint):
    sep = "&" if "?" in endpoint else "?"
    url = f"{SUPABASE_URL}/rest/v1/{endpoint}{sep}limit=10000"
    req = urllib.request.Request(
        url,
        headers={
            "apikey": SUPABASE_KEY,
            "Authorization": f"Bearer {SUPABASE_KEY}",
            "Content-Type": "application/json",
            "Prefer": "return=representation",
        },
    )
    with urllib.request.urlopen(req) as resp:
        return json.loads(resp.read().decode("utf-8"))

def is_code_or_garbage(name: str) -> bool:
    if not name:
        return True
    name = name.strip()
    if len(name) < 2:
        return True
    if re.match(r"^5\d{5}-", name):
        return True
    if re.match(r"^U[0-9A-Z]{7}$", name):
        return True
    if name.startswith("4_KABOOTAR"):
        return True
    if re.match(r"^[A-Z0-9_-]{8,}$", name, re.IGNORECASE) and not re.search(r"[a-z]", name):
        return True
    return False

def clean_name(raw: str) -> str:
    if not raw:
        return ""
    n = " ".join(raw.strip().split())
    m = re.match(r"^(\d{2,4}[A-Za-z0-9]{3,8}\s+)(.*)$", n)
    if m and len(m.group(2).strip()) > 2:
        n = m.group(2).strip()
    return n.title()

def main():
    print("Fetching Hackathon participants from Supabase...")
    hackathon_teams = supabase_get("hackathon_teams?select=lead_email")
    team_members = supabase_get("team_members?select=email")

    hackathon_emails = set()
    for ht in hackathon_teams:
        if ht.get("lead_email"):
            hackathon_emails.add(ht["lead_email"].strip().lower())
    for tm in team_members:
        if tm.get("email"):
            hackathon_emails.add(tm["email"].strip().lower())

    print(f"-> {len(hackathon_emails)} unique hackathon participant emails to exclude.")

    print("Fetching Supabase registrations & allowed_emails...")
    registrations = supabase_get("registrations?select=email,name,institution,phone")
    allowed = supabase_get("allowed_emails?select=email,full_name,role,is_active&is_active=eq.true")

    reg_map = {r["email"].strip().lower(): r for r in registrations if r.get("email")}
    allowed_map = {a["email"].strip().lower(): a for a in allowed if a.get("email")}

    print(f"Parsing Unstop CSV from {UNSTOP_PATH}...")
    unstop_map = {}
    if os.path.exists(UNSTOP_PATH):
        with open(UNSTOP_PATH, mode="r", encoding="utf-8", errors="replace") as f:
            reader = csv.DictReader(f)
            for row in reader:
                em = (row.get("Candidate's Email") or "").strip().lower()
                if not em or "@" not in em:
                    continue
                unstop_map[em] = {
                    "name": (row.get("Candidate's Name") or "").strip(),
                    "mobile": (row.get("Candidate's Mobile") or "").strip(),
                    "org": (row.get("Candidate's Organisation") or "").strip(),
                    "role": (row.get("Candidate role") or "").strip(),
                }
        print(f"-> Unstop valid emails: {len(unstop_map)}")
    else:
        print("Warning: Unstop CSV not found at specified path.")

    all_emails = set(unstop_map.keys()) | set(reg_map.keys()) | set(allowed_map.keys())
    print(f"Total union of participant emails: {len(all_emails)}")

    recipients = []
    for em in sorted(all_emails):
        if em in hackathon_emails:
            continue
        if em in PROTECTED_EMAILS or "sazzadali.b" in em or "gangireddy.s" in em:
            continue

        name = ""
        if em in unstop_map and not is_code_or_garbage(unstop_map[em]["name"]):
            name = clean_name(unstop_map[em]["name"])
        if not name and em in reg_map and not is_code_or_garbage(reg_map[em].get("name")):
            name = clean_name(reg_map[em].get("name"))
        if not name and em in allowed_map and not is_code_or_garbage(allowed_map[em].get("full_name")):
            name = clean_name(allowed_map[em].get("full_name"))
        if not name or is_code_or_garbage(name):
            prefix = em.split("@")[0]
            clean_prefix = re.sub(r"[\._\d]+", " ", prefix).strip()
            name = clean_prefix.title() if len(clean_prefix) >= 2 else "Participant"

        org = ""
        if em in unstop_map and unstop_map[em]["org"]:
            org = unstop_map[em]["org"].strip()
        if not org and em in reg_map and reg_map[em].get("institution"):
            org = reg_map[em]["institution"].strip()
        if not org:
            org = "SRM University-AP" if em.endswith("@srmap.edu.in") else "College / University"

        mobile = ""
        if em in unstop_map and unstop_map[em]["mobile"]:
            mobile = unstop_map[em]["mobile"].strip()
        if not mobile and em in reg_map and reg_map[em].get("phone"):
            mobile = str(reg_map[em]["phone"]).strip()

        recipients.append({
            "Email": em,
            "Full Name": name,
            "Institution": org,
            "Phone": mobile,
            "Role": "participant",
            "Pass_Email_Status": "",
        })

    fieldnames = ["Email", "Full Name", "Institution", "Phone", "Role", "Pass_Email_Status"]

    out_clean = r"c:\Users\sahgy\Downloads\non_hackathon_pass_recipients_clean.csv"
    with open(out_clean, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(recipients)

    out_tools = os.path.join(os.path.dirname(__file__), "non_hackathon_pass_recipients.csv")
    with open(out_tools, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(recipients)

    print(f"\nSUCCESS: Exported {len(recipients)} non-hackathon recipients.")
    print(f"Clean CSV file created at: {out_clean}")

if __name__ == "__main__":
    main()
